class ReportsAnalyticsScreen extends StatefulWidget {
  const ReportsAnalyticsScreen({super.key});

  @override
  State<ReportsAnalyticsScreen> createState() => _ReportsAnalyticsScreenState();
}

class _ReportsAnalyticsScreenState extends State<ReportsAnalyticsScreen> {
  String _period = '01 Apr 2026 - 30 Apr 2026';
  String _exportFormat = 'CSV Format';
  String _exportScope = 'All Modules';

  void _showSnack(String msg) {
    if (!mounted) return;
    ScaffoldMessenger.of(context).showSnackBar(
      SnackBar(content: Text(msg), duration: const Duration(seconds: 2)),
    );
  }

  Future<void> _generateAndDownloadReport({
    required int totalUsers,
    required int activeUsers,
    required int totalWorkouts,
    required int totalIssues,
    required int customerCount,
    required int trainerCount,
    required int advisorCount,
    required int adminCount,
  }) async {
    try {
      // 1. Log report generation event to Firebase Firestore DB
      await FirebaseFirestore.instance.collection('reports').add({
        'type': 'Custom Real-Time System Report',
        'period': _period,
        'format': _exportFormat,
        'scope': _exportScope,
        'totalUsers': totalUsers,
        'activeUsers': activeUsers,
        'totalWorkouts': totalWorkouts,
        'reportedIssues': totalIssues,
        'generatedAt': FieldValue.serverTimestamp(),
      });

      String fileName = '';
      String mimeType = 'text/plain';
      String reportContent = '';

      if (_exportFormat.contains('PDF')) {
        fileName = 'FitPulse_LiveReport_${DateTime.now().millisecondsSinceEpoch}.html';
        mimeType = 'text/html';
        reportContent = '''<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <title>FitPulse Admin System Report</title>
    <style>
        body { font-family: 'Segoe UI', Arial, sans-serif; margin: 30px; color: #1e293b; background: #ffffff; }
        h1 { color: #0d9488; border-bottom: 2px solid #0d9488; padding-bottom: 8px; font-size: 22px; }
        .meta-card { background: #f8fafc; border: 1px solid #cbd5e1; border-radius: 8px; padding: 12px; margin-bottom: 20px; }
        .badge { background: #ccfbf1; color: #0d9488; font-weight: bold; font-size: 11px; padding: 2px 8px; border-radius: 4px; }
        table { width: 100%; border-collapse: collapse; margin-top: 10px; }
        th, td { border: 1px solid #cbd5e1; padding: 10px; text-align: left; font-size: 13px; }
        th { background-color: #0f3d3a; color: white; }
        .footer { margin-top: 30px; font-size: 11px; color: #64748b; text-align: center; border-top: 1px solid #e2e8f0; padding-top: 10px; }
    </style>
</head>
<body>
    <h1>FitPulse – Official Admin System Report</h1>
    <div class="meta-card">
        <p style="margin:0;"><strong>Reporting Period:</strong> $_period &nbsp;|&nbsp; <strong>Export Scope:</strong> $_exportScope &nbsp;|&nbsp; <span class="badge">LIVE FIRESTORE DB</span></p>
        <p style="margin:4px 0 0 0; font-size:11px; color:#64748b;">Generated At: ${DateTime.now().toIso8601String()}</p>
    </div>

    <h3>📊 Live Database Performance Metrics</h3>
    <table>
        <tr><th>Metric Name</th><th>Live Value</th><th>Status</th></tr>
        <tr><td>Total Registered Users</td><td><strong>$totalUsers</strong></td><td>Active</td></tr>
        <tr><td>Active Non-Suspended Users</td><td><strong>$activeUsers</strong></td><td>Verified</td></tr>
        <tr><td>Total Published Workouts</td><td><strong>$totalWorkouts</strong></td><td>Published</td></tr>
        <tr><td>Reported Support Tickets</td><td><strong>$totalIssues</strong></td><td>Monitored</td></tr>
    </table>

    <h3 style="margin-top:20px;">👥 Real-Time User Role Distribution</h3>
    <table>
        <tr><th>Role Category</th><th>User Count</th></tr>
        <tr><td>Trainees / Customers</td><td>$customerCount</td></tr>
        <tr><td>Certified Trainers</td><td>$trainerCount</td></tr>
        <tr><td>Healthcare Advisors (Doctors)</td><td>$advisorCount</td></tr>
        <tr><td>System Administrators</td><td>$adminCount</td></tr>
    </table>

    <div class="footer">
        Confidential – Generated by FitPulse Kinetic Pulse Analytics Engine v2.4.0
    </div>
</body>
</html>''';
      } else if (_exportFormat.contains('JSON')) {
        fileName = 'FitPulse_LiveReport_${DateTime.now().millisecondsSinceEpoch}.json';
        mimeType = 'application/json';
        reportContent = jsonEncode({
          'report': 'FitPulse Real-Time System Report',
          'period': _period,
          'scope': _exportScope,
          'generatedAt': DateTime.now().toIso8601String(),
          'metrics': {
            'totalUsers': totalUsers,
            'activeUsers': activeUsers,
            'totalWorkouts': totalWorkouts,
            'reportedIssues': totalIssues,
          },
          'roles': {
            'customers': customerCount,
            'trainers': trainerCount,
            'advisors': advisorCount,
            'admins': adminCount,
          }
        });
      } else {
        fileName = 'FitPulse_LiveReport_${DateTime.now().millisecondsSinceEpoch}.csv';
        mimeType = 'text/csv';
        reportContent = '''Metric,Value
Reporting Period,$_period
Export Scope,$_exportScope
Generated At,${DateTime.now().toIso8601String()}
Total Registered Users,$totalUsers
Active Non-Suspended Users,$activeUsers
Total Workouts,$totalWorkouts
Reported Support Issues,$totalIssues
Customer Trainees,$customerCount
Certified Trainers,$trainerCount
Healthcare Advisors,$advisorCount
System Admins,$adminCount
''';
      }

      final bytes = utf8.encode(reportContent);

      // 2. Download Report File Directly to Admin's Device / Downloads Folder
      await DownloadHelper.downloadFile(
        bytes: bytes,
        fileName: fileName,
        mimeType: mimeType,
      );

      _showSnack('Report file ($fileName) downloaded directly to your Downloads folder!');
    } catch (e) {
      _showSnack('Failed to generate report: $e');
    }
  }

